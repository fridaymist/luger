// Generates Luger's secrets once:
//   luger.config.json  -> public values compiled into the app (safe to commit)
//   .secrets.env       -> private values for `supabase secrets set --env-file .secrets.env` (never commit)
// Usage: node scripts/setup-secrets.mjs <supabase-project-ref> <your-roblox-user-id>
import { createCipheriv, createHash, createHmac, generateKeyPairSync, randomBytes } from 'node:crypto'
import { existsSync, writeFileSync } from 'node:fs'

const [ref, ownerId] = process.argv.slice(2)
if (!ref || !/^[a-z0-9]{20}$/.test(ref) || !ownerId || !/^\d+$/.test(ownerId)) {
  console.error('Usage: node scripts/setup-secrets.mjs <supabase-project-ref> <your-roblox-user-id>')
  console.error('The project ref is the 20 letters in your Supabase URL: https://<ref>.supabase.co')
  process.exit(1)
}
if (existsSync('.secrets.env') && !process.argv.includes('--force')) {
  console.error('.secrets.env already exists. Re-running would sign everyone out. Add --force if you really mean it.')
  process.exit(1)
}
const pepper = randomBytes(32).toString('hex')
const vault = randomBytes(32).toString('hex')

// Your own lifetime key, so you can sign in before anything else is set up.
// Same format and hashing as the server (supabase/functions/_shared/util.ts).
const ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ'
let body = ''
for (const b of randomBytes(15)) body += ALPHABET[b & 31]
let sum = 0
for (const c of body) sum = (sum * 31 + ALPHABET.indexOf(c)) % 32
const full = body + ALPHABET[sum]
const ownerKey = 'LUGER-' + full.match(/.{4}/g).join('-')
const hash = createHmac('sha256', pepper).update(full).digest('hex')
const iv = randomBytes(12)
const cipher = createCipheriv('aes-256-gcm', createHash('sha256').update(vault).digest(), iv)
const sealed = `${iv.toString('base64')}.${Buffer.concat([cipher.update(ownerKey), cipher.final(), cipher.getAuthTag()]).toString('base64')}`
writeFileSync('supabase/migrations/0002_owner_key.sql', `-- Generated by scripts/setup-secrets.mjs: the owner's lifetime key (stored hashed).\n` +
  `insert into keys (key_hash, key_hint, key_sealed, label, kind, duration_s, starts_on_use, max_devices, bound_roblox_id, source, note)\n` +
  `values ('${hash}', '${full.slice(-4)}', '${sealed}', 'Owner', 'staff', null, false, 3, ${ownerId}, 'owner', 'Created during setup');\n`)

const { privateKey, publicKey } = generateKeyPairSync('ed25519')
const priv = privateKey.export({ format: 'jwk' })
const pub = publicKey.export({ format: 'jwk' })
writeFileSync('luger.config.json', JSON.stringify({
  functions: `https://${ref}.supabase.co/functions/v1`,
  publicKey: pub,
  site: 'https://lugerhub.fun',
  discord: 'https://discord.gg/zTnwbjHu4e'
}, null, 2) + '\n')
writeFileSync('.secrets.env', [
  `LUGER_SIGNING_JWK='${JSON.stringify(priv)}'`,
  `LUGER_KEY_PEPPER=${pepper}`,
  `LUGER_KEY_VAULT=${vault}`,
  `OWNER_ROBLOX_ID=${ownerId}`,
  `LUGER_SITE_URL=https://lugerhub.fun`,
  `STRIPE_SECRET_KEY=`,
  `STRIPE_WEBHOOK_SECRET=`,
  `STRIPE_AUTOMATIC_TAX=false`,
  `LOOTLABS_LINK=`,
  `LINKVERTISE_USER_ID=`,
  `LINKVERTISE_API_TOKEN=`,
  `WORKINK_LINK=`,
  ''
].join('\n'))
writeFileSync('web/config.js', `// Generated by scripts/setup-secrets.mjs\nwindow.LUGER = {\n  functions: 'https://${ref}.supabase.co/functions/v1',\n  download: 'https://github.com/fridaymist/luger/releases/latest',\n  discord: 'https://discord.gg/zTnwbjHu4e'\n}\n`)
console.log('Wrote luger.config.json, .secrets.env, web/config.js and your owner key.')
console.log(`\nYour owner key (lifetime, up to 3 devices). Save it somewhere safe:\n\n  ${ownerKey}\n`)
console.log('Next: fill the empty Stripe and ad-network lines in .secrets.env, then run:')
console.log('  npx supabase secrets set --env-file .secrets.env')
